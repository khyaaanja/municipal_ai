class Command(BaseCommand):
    help = "Seed KnowledgeBase with Nepali-language Bhaktapur content"

    def add_arguments(self, parser):
        parser.add_argument(
            '--update', action='store_true',
            help='Update existing entries (default: skip if title exists)'
        )

    def handle(self, *args, **options):
        from chatbot.models import KnowledgeBase

        self.stdout.write(self.style.MIGRATE_HEADING("=== Seeding Nepali Knowledge Base ==="))
        created = updated = skipped = 0

        for category, title, content, keywords, priority in NEPALI_ENTRIES:
            existing = KnowledgeBase.objects.filter(title=title).first()

            if existing and not options['update']:
                self.stdout.write(f"  ↷ Skipped (exists): {title}")
                skipped += 1
                continue

            if existing and options['update']:
                KnowledgeBase.objects.filter(pk=existing.pk).update(
                    content=content,
                    category=category,
                    keywords=keywords,
                    priority=priority,
                    language='ne',
                    is_active=True,
                )
                self.stdout.write(self.style.WARNING(f"  ↻ Updated: {title}"))
                updated += 1
            else:
                KnowledgeBase.objects.create(
                    title=title,
                    content=content,
                    category=category,
                    keywords=keywords,
                    language='ne',
                    priority=priority,
                    is_active=True,
                    auto_generated=False,
                )
                self.stdout.write(self.style.SUCCESS(f"  ✓ Created: {title}"))
                created += 1

        self.stdout.write(self.style.SUCCESS(
            f"\nDone! {created} created, {updated} updated, {skipped} skipped."
        ))
        if created + updated > 0:
            self.stdout.write(
                self.style.NOTICE(
                    "Run 'python manage.py shell -c \"from chatbot.tasks import embed_new_kb_entries_batch; embed_new_kb_entries_batch()\"' "
                    "to vectorize the new entries immediately."
                )
            )
